/**
 * Seed a freshly-created workspace with the mock project (idempotent — never
 * overwrites an existing manifest/assets, so a returning user keeps their work).
 */
export function seedWorkspace(workspacePath) {
  try {
    // Ensure the workspace directory exists (a brand-new user has none yet).
    fs.mkdirSync(workspacePath, { recursive: true });
    const manifestPath = path.join(workspacePath, MANIFEST_FILE);
    if (!fs.existsSync(manifestPath)) {
      fs.writeFileSync(manifestPath, JSON.stringify(buildManifest(), null, 2));
    }
    for (const s of SOURCES) {
      if (s.type !== 'image') continue;
      // Copy the bundled real drawing if we have one; else write a placeholder SVG.
      if (hasSeedImage(s.id)) {
        const dst = path.join(workspacePath, `${s.id}.${SEED_IMAGE_EXT}`);
        if (!fs.existsSync(dst)) {
          fs.copyFileSync(path.join(SEED_ASSETS_DIR, `${s.id}.${SEED_IMAGE_EXT}`), dst);
        }
      } else {
        const file = path.join(workspacePath, `${s.id}.svg`);
        if (!fs.existsSync(file)) fs.writeFileSync(file, mockSvg(s.title));
      }
    }
    const claudeMd = path.join(workspacePath, 'CLAUDE.md');
    if (!fs.existsSync(claudeMd)) fs.writeFileSync(claudeMd, CLAUDE_MD);
  } catch (err) {
    console.error('[bldr] seedWorkspace failed for', workspacePath, err?.message || err);
  }
}

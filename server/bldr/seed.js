/**
 * bldr — project data sources, seed mockups, and the bldr-backend agent brief.
 *
 * Each project has a fixed set of DATA SOURCES; each source has a TYPE that
 * decides how its pane renders. `bldr.json` (in the project folder) is the
 * single source of truth: { name, sources: { <id>: {type, ...value, rev} }, locks }.
 *
 * We seed MOCKUPS so a pane shows something immediately. The image panes are
 * seeded from real BTI proposal drawings (extracted from the PDF proposals on the
 * shared drive — see server/bldr/seed-assets/) so the mockup output already looks
 * like the real deliverable. Other agents fill the real per-project renders later
 * (same shape: rewrite the asset in the workspace + bump rev). If a seed asset is
 * missing we fall back to a labelled placeholder SVG so a pane is never blank.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

export const MANIFEST_FILE = 'bldr.json';

// Bundled real-drawing seed assets (BTI "Expo Valley Guard House" proposal set).
const SEED_ASSETS_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), 'seed-assets');
const SEED_IMAGE_EXT = 'jpg';

// The defined registry of data sources (instantiated per project on creation).
// Extend this list to add new panes in the future.
export const SOURCES = [
  { id: 'top_view', title: 'Top view', type: 'image' },
  { id: 'section', title: 'Section', type: 'image' },
  { id: 'elevations', title: 'Elevations', type: 'image' },
  { id: 'front_view', title: 'Front view', type: 'image' },
  { id: 'costs', title: 'Costs', type: 'cost-table' },
  { id: 'location', title: 'Location', type: 'map-cesium' },
];

// Lock groups: sources that must change together. In the current MOCKUP phase the
// image panes (top_view / section / elevations / front_view) are REAL BTI proposal
// drawings and must NOT be regenerated by the agent, so they are deliberately left
// out of every group. Only the computed data panes move together.
export const LOCK_GROUPS = [
  ['costs', 'location'],
];

const RED = '#D52027';

// A simple labelled placeholder image so a pane shows something immediately.
function mockSvg(label) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600" viewBox="0 0 800 600">
  <rect width="800" height="600" fill="#141414"/>
  <rect x="40" y="40" width="720" height="520" fill="none" stroke="${RED}" stroke-width="2"/>
  <line x1="40" y1="300" x2="760" y2="300" stroke="#2a2a2a" stroke-width="1"/>
  <line x1="400" y1="40" x2="400" y2="560" stroke="#2a2a2a" stroke-width="1"/>
  <text x="400" y="300" fill="#9a9a9a" font-family="sans-serif" font-size="34" font-weight="600" text-anchor="middle" dominant-baseline="middle">${label}</text>
  <text x="400" y="345" fill="#5a5a5a" font-family="sans-serif" font-size="16" text-anchor="middle">mock — to be rendered</text>
</svg>`;
}

const MOCK_COSTS = {
  name: '3D building cost',
  currency: 'AED',
  rows: [
    { item: 'Foundation', qty: 1, unit: 'lot', cost: 120000 },
    { item: '3D-printed walls', qty: 210, unit: 'm²', cost: 480000 },
    { item: 'Roof & slab', qty: 1, unit: 'lot', cost: 160000 },
    { item: 'MEP (mech/elec/plumb)', qty: 1, unit: 'lot', cost: 140000 },
    { item: 'Finishes', qty: 1, unit: 'lot', cost: 271500 },
  ],
  total: 1171500,
};

// Jumeirah Village Circle, Dubai — matches the old app's context block.
const MOCK_LOCATION = {
  lat: 25.0753,
  lng: 55.1380,
  zoom: 17,
  label: 'Jumeirah Village Circle, Dubai',
  model: null,
};

// True if a bundled real-drawing seed asset exists for this source id.
function hasSeedImage(id) {
  return fs.existsSync(path.join(SEED_ASSETS_DIR, `${id}.${SEED_IMAGE_EXT}`));
}

function buildManifest() {
  const sources = {};
  for (const s of SOURCES) {
    if (s.type === 'image') {
      // Prefer the bundled real drawing; fall back to a placeholder SVG.
      const ext = hasSeedImage(s.id) ? SEED_IMAGE_EXT : 'svg';
      sources[s.id] = { type: 'image', path: `${s.id}.${ext}`, rev: 1 };
    } else if (s.type === 'cost-table') {
      sources[s.id] = { type: 'cost-table', name: MOCK_COSTS.name, data: MOCK_COSTS, rev: 1 };
    } else if (s.type === 'map-cesium') {
      sources[s.id] = { type: 'map-cesium', data: MOCK_LOCATION, rev: 1 };
    }
  }
  return { name: '3D Building', sources, locks: LOCK_GROUPS };
}

